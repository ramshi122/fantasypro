/**
 * WhatsApp Direct Share
 * =====================
 * Generate a WhatsApp-friendly text summary of a team and a wa.me deep link
 * that opens WhatsApp with the message pre-filled.
 *
 * Public API:
 *   - generateTeamText(team, opts?): string
 *   - generateWhatsAppLink(text, phone?): string
 *   - shareTeamOnWhatsApp(team, opts?): void   (opens new tab)
 *
 * Additive — does NOT modify any existing share module.
 */

import type { MatchPlayer, TeamRow } from "./api";
import { roleLabel, shortName, teamColor } from "./format";

export interface GenerateTeamTextOpts {
  matchName?: string;
  team1Name?: string;
  team2Name?: string;
  platform?: string;
  teamNumber?: number | string;
  includeHashtags?: boolean;
}

/**
 * Build a WhatsApp-friendly plain-text summary of a team.
 *
 * Example output:
 *   🏏 *Apna Cricket — IND vs AUS (Team 1)*
 *   Platform: Dream11
 *
 *   WK:  Rahul (C)
 *   BAT:  Rohit, Kohli
 *   AR:   Hardik
 *   BOWL: Bumrah (VC)
 *
 *   Captain: Rahul
 *   Vice Captain: Bumrah
 *
 *   Generated by Apna Cricket 🏏
 *   #ApnaCricket #Fantasy
 */
export function generateTeamText(team: TeamRow, opts: GenerateTeamTextOpts = {}): string {
  const players: MatchPlayer[] = team.players || [];
  const captainId = String(team.captain ?? team.c ?? "");
  const viceCaptainId = String(team.viceCaptain ?? team.vc ?? team.vicecaptain ?? "");

  const lines: string[] = [];

  // Header
  const matchTitle = opts.matchName || "Match";
  const teamLabel = opts.teamNumber ? `Team ${opts.teamNumber}` : "Team";
  lines.push(`🏏 *Apna Cricket — ${matchTitle} (${teamLabel})*`);
  if (opts.platform) lines.push(`Platform: ${opts.platform}`);
  lines.push("");

  // Group by role
  const byRole: Record<string, MatchPlayer[]> = { WK: [], BAT: [], AR: [], BOWL: [] };
  for (const p of players) {
    const role =
      (typeof p.role === "string" ? p.role : "") ||
      roleLabel(p.player_type) ||
      "BAT";
    const key = ["WK", "BAT", "AR", "BOWL"].includes(role) ? role : "BAT";
    byRole[key].push(p);
  }

  for (const r of ["WK", "BAT", "AR", "BOWL"] as const) {
    const list = byRole[r];
    if (list.length === 0) continue;
    const names = list.map((p) => {
      const id = String(
        p.player_fixed_id ?? p.pl_id ?? p.pid ?? p.id ?? p.name ?? ""
      );
      const nm = String(p.name || p.shortName || "?");
      let suffix = "";
      if (id && id === captainId) suffix = " (C)";
      else if (id && id === viceCaptainId) suffix = " (VC)";
      return nm + suffix;
    });
    lines.push(`${r}: ${names.join(", ")}`);
  }

  // Captain / VC explicit
  const captain = players.find((p) =>
    String(p.player_fixed_id ?? p.pl_id ?? p.pid ?? p.id ?? "") === captainId
  );
  const viceCaptain = players.find((p) =>
    String(p.player_fixed_id ?? p.pl_id ?? p.pid ?? p.id ?? "") === viceCaptainId
  );

  lines.push("");
  if (captain) lines.push(`Captain: ${captain.name || captain.shortName || "?"}`);
  if (viceCaptain) lines.push(`Vice Captain: ${viceCaptain.name || viceCaptain.shortName || "?"}`);

  // Footer
  lines.push("");
  lines.push("Generated by Apna Cricket 🏏");
  if (opts.includeHashtags !== false) {
    lines.push("#ApnaCricket #Fantasy #Dream11");
  }

  return lines.join("\n");
}

/**
 * Build a wa.me deep link with the given text (URL-encoded).
 * If `phone` is supplied (E.164 format, no +), opens a direct chat.
 */
export function generateWhatsAppLink(text: string, phone?: string): string {
  const encoded = encodeURIComponent(text);
  const base = phone
    ? `https://wa.me/${phone.replace(/[^\d]/g, "")}`
    : `https://wa.me`;
  return `${base}?text=${encoded}`;
}

/**
 * Open WhatsApp (new tab) with the team summary pre-filled.
 * No-op on the server.
 */
export function shareTeamOnWhatsApp(team: TeamRow, opts?: GenerateTeamTextOpts & { phone?: string }): void {
  if (typeof window === "undefined") return;
  const text = generateTeamText(team, opts);
  const url = generateWhatsAppLink(text, opts?.phone);
  window.open(url, "_blank", "noopener,noreferrer");
}

/**
 * Quick helper: format a player's short label for compact rendering.
 */
export function playerShortLabel(p: MatchPlayer): string {
  const name = String(p.name || p.shortName || "?");
  const team = String(p.team || p.team_name || "");
  const color = teamColor(team);
  return `${shortName(name)} (${team}) [${color}]`;
}
